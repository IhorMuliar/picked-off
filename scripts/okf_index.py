#!/usr/bin/env python3
"""Rebuild every index.md in an OKF v0.2 bundle and validate its concepts.

Usage: okf_index.py <bundle-root> [--check] [folder=Type[|Type...] ...]

The root index.md keeps everything above the GENERATED marker (frontmatter
with okf_version, plus the bundle preamble); everything below it, and every
other index.md, is rewritten. --check writes nothing and exits 1 when an
index is stale or a concept is invalid.
"""
import os
import re
import sys

MARKER = "<!-- GENERATED by okf_index.py below this line; do not edit -->"
RESERVED = {"index.md", "log.md"}
REQUIRED = ("type", "description", "generated")
LINK = re.compile(r"\]\(([^)\s#]+\.md)(?:#[^)]*)?\)")


def frontmatter(text):
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return None
    keys = {}
    for line in lines[1:]:
        if line.strip() == "---":
            return keys
        m = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if m:
            keys[m.group(1)] = m.group(2).strip().strip("\"'")
    return None


def concepts_in(path):
    return sorted(
        f for f in os.listdir(path)
        if f.endswith(".md") and f not in RESERVED and os.path.isfile(os.path.join(path, f))
    )


def subdirs(path):
    return sorted(
        d for d in os.listdir(path)
        if not d.startswith(".") and os.path.isdir(os.path.join(path, d)) and has_concepts(os.path.join(path, d))
    )


def has_concepts(path):
    for _, _, files in os.walk(path):
        if any(f.endswith(".md") and f not in RESERVED for f in files):
            return True
    return False


def count(path):
    return sum(
        1 for _, _, files in os.walk(path) for f in files if f.endswith(".md") and f not in RESERVED
    )


def listing(root, path, metas):
    out = []
    dirs = subdirs(path)
    if dirs:
        out += ["# Sections", ""]
        for d in dirs:
            n = count(os.path.join(path, d))
            out.append("* [%s](%s/) - %d concept%s" % (d, d, n, "" if n == 1 else "s"))
        out.append("")
    files = concepts_in(path)
    if files:
        heading = "Concepts" if path == root else os.path.basename(path)
        out += ["# %s" % heading, ""]
        for f in files:
            meta = metas.get(os.path.join(path, f)) or {}
            title = meta.get("title") or f[:-3]
            desc = meta.get("description", "")
            out.append("* [%s](%s) - %s" % (title, f, desc) if desc else "* [%s](%s)" % (title, f))
        out.append("")
    return "\n".join(out)


def main(argv):
    args = [a for a in argv if not a.startswith("--")]
    check = "--check" in argv
    if not args:
        sys.exit(__doc__)
    root = os.path.abspath(args[0])
    rules = {}
    for rule in args[1:]:
        folder, _, types = rule.partition("=")
        rules[folder.strip("/")] = set(types.split("|"))

    errors, metas, stale = [], {}, []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        for f in sorted(filenames):
            if not f.endswith(".md") or f in RESERVED:
                continue
            p = os.path.join(dirpath, f)
            rel = os.path.relpath(p, root)
            with open(p, encoding="utf-8") as fh:
                text = fh.read()
            meta = frontmatter(text)
            if meta is None:
                errors.append("%s: no parseable frontmatter" % rel)
                continue
            metas[p] = meta
            for key in REQUIRED:
                if not meta.get(key) and not (key == "generated" and key in meta):
                    errors.append("%s: missing or empty '%s'" % (rel, key))
            top = rel.split(os.sep)[0] if os.sep in rel else ""
            if top in rules and meta.get("type") not in rules[top]:
                errors.append("%s: type '%s' not allowed in %s/ (allowed: %s)"
                              % (rel, meta.get("type"), top, ", ".join(sorted(rules[top]))))
            for target in LINK.findall(text):
                if "://" in target:
                    continue
                dest = os.path.join(root, target.lstrip("/")) if target.startswith("/") \
                    else os.path.join(dirpath, target)
                if not os.path.isfile(os.path.normpath(dest)):
                    errors.append("%s: broken link %s" % (rel, target))

    for dirpath, dirnames, _ in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        if dirpath != root and not has_concepts(dirpath):
            continue
        idx = os.path.join(dirpath, "index.md")
        if os.path.islink(idx):
            errors.append("%s: is a symlink; refusing to write through it" % os.path.relpath(idx, root))
            continue
        old = open(idx, encoding="utf-8").read() if os.path.exists(idx) else ""
        body = listing(root, dirpath, metas)
        if dirpath == root:
            root_meta = frontmatter(old) or {}
            if MARKER not in old or "okf_version" not in root_meta:
                errors.append("index.md: root index needs okf_version frontmatter, a preamble and the marker line")
                continue
            new = old.split(MARKER)[0] + MARKER + "\n\n" + body
        else:
            new = body
        if new != old:
            stale.append(os.path.relpath(idx, root))
            if not check:
                with open(idx, "w", encoding="utf-8") as fh:
                    fh.write(new)

    for e in errors:
        print("okf: " + e, file=sys.stderr)
    if check and stale:
        print("okf: stale index, run make knowledge: " + ", ".join(stale), file=sys.stderr)
    if errors or (check and stale):
        sys.exit(1)
    if stale:
        print("okf: rebuilt " + ", ".join(stale))


if __name__ == "__main__":
    main(sys.argv[1:])
